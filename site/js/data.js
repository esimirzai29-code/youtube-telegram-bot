function getCategory(id) {
  return CATEGORIES.find(c => c.id === id) || { name: id, icon: "📝" };
}
function getArticle(id) {
  return ARTICLES.find(a => a.id === Number(id));
}
function countByCategory(catId) {
  return ARTICLES.filter(a => a.category === catId).length;
}
function allTags() {
  const map = {};
  ARTICLES.forEach(a => a.tags.forEach(t => { map[t] = (map[t] || 0) + 1; }));
  return Object.entries(map).sort((x, y) => y[1] - x[1]);
}
